"""V3s report: Spring-Gaus / PhysTwin transfer with the V3 prior vs the V2-prior numbers (v3k-A, v3l).

  .venv/bin/python -I scripts/v3s/report.py
1. Prior-independent rows are copied (not rerun) from v3l into data/v3s (marked in docs/v3s/REUSED.json): per-scene GT-E
   replay (gtE.json), PhysTwin static / rigid-follow / jelly-mean-start evals and search, smoke, baselines.
2. scripts/v3l/make_results.py is run unchanged except for its input/output paths (generated copy
   scripts/v3s/_make_results_v3s.py) -> docs/v3s/RESULTS_V3L_PROTOCOL.json (same schema as docs/v3l/RESULTS.json).
3. v3k-A (30-frame in-target refinement, 14 scenes): |dlog10 E|, Spearman, pairwise order at k = 0/4/12, V3 vs V2 prior,
   paired scene bootstrap (2000, seed 17) of the V3-V2 difference in |dlog10 E|.
-> docs/v3s/RESULTS.json, docs/v3s/RESULTS_ZH.md
"""
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
SCENES = ['torus', 'duck', 'apple', 'C', 'E', 'V', 'banana', 'chess', 'cream', 'cross', 'doraemon', 'droplet', 'rope', 'toothpaste']
PRIMARY = ['torus', 'duck', 'apple']
KS = ['0', '4', '12']


def rd(p):
    try:
        return json.loads(Path(p).read_text())
    except (OSError, ValueError):
        return None


def reuse():
    log = []
    for s in SCENES:
        src, dst = ROOT / f'data/v3l/sg/{s}/gtE.json', ROOT / f'data/v3s/sg/{s}/gtE.json'
        if src.exists() and not dst.exists():
            dst.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(src, dst); log.append(str(dst.relative_to(ROOT)))
    for f in ('eval_static.json', 'eval_rigid_follow.json', 'eval_mpm_jellymean_b0.json', 'eval_mpm_jellymean_b12.json',
              'search_jellymean.json', 'smoke.json', 'baselines.json'):
        src, dst = ROOT / f'data/v3l/pt/{f}', ROOT / f'data/v3s/pt/{f}'
        if src.exists() and not dst.exists():
            dst.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(src, dst); log.append(str(dst.relative_to(ROOT)))
    old = rd(ROOT / 'docs/v3s/REUSED.json') or {'note': 'prior-independent files copied unchanged from data/v3l (not rerun)', 'files': []}
    old['files'] = sorted(set(old['files']) | set(log)); (ROOT / 'docs/v3s/REUSED.json').write_text(json.dumps(old, indent=1))


def v3l_protocol_results():
    src = (ROOT / 'scripts/v3l/make_results.py').read_text()
    for a, b in (("'data/v3l/prior20.json'", "'data/v3s/prior20.json'"), ("'data/v3l/sg'", "'data/v3s/sg'"), ("'data/v3l/pt'", "'data/v3s/pt'"),
                 ("'docs/v3l/RESULTS.json'", "'docs/v3s/RESULTS_V3L_PROTOCOL.json'"), ("'data/v3k/sg'", "'data/v3s/kA'")):
        assert src.count(a) >= 1, a; src = src.replace(a, b)
    gen = ROOT / 'scripts/v3s/_make_results_v3s.py'
    gen.write_text('# GENERATED by scripts/v3s/report.py from scripts/v3l/make_results.py (paths only). Do not edit.\n' + src)
    r = subprocess.run([sys.executable, '-I', str(gen)], cwd=ROOT, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(r.stderr)
    return rd(ROOT / 'docs/v3s/RESULTS_V3L_PROTOCOL.json'), r.stdout


def kA():
    import importlib.util  # scripts/v3k/report.py helpers (rank_metrics), loaded by path (this file is also called report.py)
    spec = importlib.util.spec_from_file_location('v3k_report', ROOT / 'scripts/v3k/report.py'); K = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(K)
    out = {}
    for tag, d in (('v3_prior', ROOT / 'data/v3s/kA'), ('v2_prior', ROOT / 'data/v3k/sg')):
        st = {s: rd(d / s / 'prior.json') for s in SCENES}
        st = {s: v for s, v in st.items() if v and v.get('complete') and v.get('gt_log10E') is not None}
        e = {'n_scenes': len(st), 'scenes': sorted(st)}
        for k in KS:
            pred = [st[s]['budgets'][k]['log10E'] for s in sorted(st)]; gt = [st[s]['gt_log10E'] for s in sorted(st)]
            e[f'k{k}'] = K.rank_metrics(pred, gt) if len(st) >= 3 else None
        e['per_scene'] = {s: {'gt': st[s]['gt_log10E'], **{f'k{k}': st[s]['budgets'][k]['log10E'] for k in KS},
                              'prior_nu': st[s].get('prior_nu')} for s in sorted(st)}
        e['sims_used_mean'] = float(np.mean([len(st[s]['evals']) for s in st])) if st else None
        e['search_seconds_mean'] = float(np.mean([sum(x['seconds'] for x in st[s]['evals']) for s in st])) if st else None
        out[tag] = e
    common = sorted(set(out['v3_prior']['per_scene']) & set(out['v2_prior']['per_scene']))
    rng = np.random.default_rng(17); paired = {}
    for k in KS:
        d = np.array([abs(out['v3_prior']['per_scene'][s][f'k{k}'] - out['v3_prior']['per_scene'][s]['gt'])
                      - abs(out['v2_prior']['per_scene'][s][f'k{k}'] - out['v2_prior']['per_scene'][s]['gt']) for s in common])
        if len(d):
            m = d[rng.integers(0, len(d), (2000, len(d)))].mean(1)
            paired[f'k{k}'] = {'mean_diff_abs_dlog10E_v3_minus_v2': float(d.mean()), 'ci95': [float(np.quantile(m, .025)), float(np.quantile(m, .975))], 'n': len(d)}
    out['paired_v3_minus_v2'] = paired
    jm = {s: rd(ROOT / f'data/v3k/sg/{s}/jellymean.json') for s in SCENES}
    out['uninformed_jellymean_v2_REUSED'] = {f'k{k}': float(np.mean([abs(v['budgets'][k]['log10E'] - v['gt_log10E']) for v in jm.values()
                                                                    if v and v.get('gt_log10E') is not None and k in v.get('budgets', {})])) for k in KS}
    return out


def f(v, n=4):
    return '–' if v is None else (f'{v:.{n}f}' if isinstance(v, (float, int)) else str(v))


def main():
    reuse()
    new, stdout = v3l_protocol_results()
    old = rd(ROOT / 'docs/v3l/RESULTS.json')
    A = kA()
    arms = ('prior20', 'prior20_refine_b4', 'prior20_refine_b12')
    keys = ('abs_dlog10E', 'fit_cd_mean', 'future_cd_mean', 'future_psnr_mean', 'future_ssim_mean', 'future_mask_iou_mean', 'fit_psnr_mean', 'fit_ssim_mean')
    delta = {}
    for g in ('primary3', 'all14'):
        for a in arms:
            n, o = new['part1_mean'].get(g, {}).get(a), old['part1_mean'].get(g, {}).get(a)
            if n and o:
                delta.setdefault(g, {})[a] = {k: {'v3': n.get(k), 'v2': o.get(k), 'delta': (n[k] - o[k]) if n.get(k) is not None and o.get(k) is not None else None} for k in keys}
    per_scene = {}
    for s in SCENES:
        for a in arms:
            n, o = new['part1'][s]['arms'].get(a), old['part1'][s]['arms'].get(a)
            if n and o and not n.get('failed') and not o.get('failed'):
                per_scene.setdefault(s, {})[a] = {k: {'v3': n.get(k), 'v2': o.get(k)} for k in ('log10E', 'abs_dlog10E', 'fit_cd_mean', 'future_cd_mean', 'future_psnr_mean', 'future_ssim_mean')}
    sg_off = {g: {k: float(np.mean([new['part1'][s]['springgaus_official'][k] for s in PRIMARY])) for k in ('fit_cd_mean', 'future_cd_mean')} for g in ('primary3',)}
    pt_keys = ('chamfer_train', 'chamfer_test', 'track_train', 'track_test')
    p2n, p2o = new['part2'], old['part2']
    pt = {t: {k: {'v3': (p2n.get(t) or {}).get(k), 'v2': (p2o.get(t) or {}).get(k)} for k in pt_keys} for t in ('mpm_prior_b0', 'mpm_prior_b12')}
    pt['prior_log10E'] = {'v3': (p2n.get('prior_on_rgb') or {}).get('log10_E_Pa_at_rho1000'), 'v2': (p2o.get('prior_on_rgb') or {}).get('log10_E_Pa_at_rho1000')}
    pt['law_votes'] = {'v3': (p2n.get('prior_on_rgb') or {}).get('law_votes'), 'v2': (p2o.get('prior_on_rgb') or {}).get('law_votes')}
    pt['refined_log10E'] = {'v3': ((p2n.get('search_prior') or {}).get('best') or {}).get('log10E'), 'v2': ((p2o.get('search_prior') or {}).get('best') or {}).get('log10E')}
    pt['search_seconds'] = {'v3': (p2n.get('search_prior') or {}).get('search_seconds'), 'v2': (p2o.get('search_prior') or {}).get('search_seconds')}
    for t in ('official_phystwin', 'rigid_follow', 'static', 'mpm_jellymean_b12'):
        pt[t + '_REUSED'] = {k: (p2n.get(t) or {}).get(k) for k in pt_keys}
    prior = rd(ROOT / 'data/v3s/prior20.json') or {}
    res = {'stage': 'v3s', 'created_utc': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
           'prior_sources': rd(ROOT / 'docs/v3s/PRIOR_SOURCES.json'),
           'protocol': 'unchanged from docs/v3k/PROTOCOL.json (part A) and docs/v3l/PROTOCOL.json; only the prior checkpoints / decoding stats differ '
                       '(scripts/v3s/prior_v3.py = scripts/v3l/prior20.py / pt_prior.py with the V3 runs; verified to reproduce the V2 prior20 '
                       'values exactly when given the V2 runs: data/v3s/smoke/prior20_v2.json, max |dz| = 0)',
           'reused_not_rerun': ['Spring-Gaus official (v3g/v3l)', 'PhysTwin official (v3g)', 'GT-E replay diagnostics', 'static / renderer-ceiling rows',
                                'PhysTwin static / rigid-follow / jelly-mean start', 'v3k-A jelly-mean (uninformed) start and diag arms'],
           'springgaus_v3l_protocol': {'mean_delta': delta, 'per_scene': per_scene, 'springgaus_official_mean': sg_off,
                                       'full_v3_prior_results': 'docs/v3s/RESULTS_V3L_PROTOCOL.json'},
           'springgaus_v3kA_30frame_refine': A, 'phystwin': pt,
           'prior_predictions': {s: {'f20_log10E': v.get('f20', {}).get('log10_E_Pa_at_rho1000'), 'f30_log10E': v.get('f30_recomputed', {}).get('log10_E_Pa_at_rho1000'),
                                     'gt_log10E': v.get('gt_log10E')} for s, v in prior.get('scenes', {}).items()}}
    (ROOT / 'docs/v3s/RESULTS.json').write_text(json.dumps(res, indent=1, ensure_ascii=False))
    # ------------------------------------------------------------------ markdown
    nm = {'prior20': '只用先验（0–19 帧）', 'prior20_refine_b4': '先验 + 4 次', 'prior20_refine_b12': '先验 + 12 次'}
    L = ['# V3s：用 V3 先验重跑 Spring-Gaus / PhysTwin 迁移（按对方指标）', f"自动生成：`scripts/v3s/report.py`，{res['created_utc']}。数据：`docs/v3s/RESULTS.json`。", '',
         '- 协议与 v3k-A、v3l 完全相同，只换先验（V3 先验检查点与解码统计量）。官方 Spring-Gaus / PhysTwin、GT-E 重放、静止 / 刚性跟手、无信息起点均为不依赖先验的行，直接沿用，不重跑。',
         '- 先验封装 `scripts/v3s/prior_v3.py` 在给定 V2 runs 时逐位复现 v3l 的 prior20（|Δz| = 0）。', '']
    for g, title in (('primary3', '3 个主场景（torus/duck/apple）平均'), ('all14', '14 个场景平均')):
        if g not in delta:
            continue
        L += [f'## Spring-Gaus 合成，v3l 协议：{title}', '', '| 方法 | \\|Δlog10 E\\| V3（V2） | 拟合 CD | 未来 CD | 未来 PSNR | 未来 SSIM | 未来 IoU | 拟合 PSNR |', '|---|---|---|---|---|---|---|---|']
        for a in arms:
            if a in delta[g]:
                d = delta[g][a]
                L.append(f"| {nm[a]} | {f(d['abs_dlog10E']['v3'], 2)} ({f(d['abs_dlog10E']['v2'], 2)}) | " + ' | '.join(
                    f"{f(d[k]['v3'], n)} ({f(d[k]['v2'], n)})" for k, n in (('fit_cd_mean', 4), ('future_cd_mean', 4), ('future_psnr_mean', 2),
                                                                         ('future_ssim_mean', 3), ('future_mask_iou_mean', 3), ('fit_psnr_mean', 2))) + ' |')
        if g == 'primary3':
            L.append(f"| Spring-Gaus 官方（沿用） | – | {f(sg_off['primary3']['fit_cd_mean'])} | {f(sg_off['primary3']['future_cd_mean'])} | | | | |")
        L.append('')
    L += ['## 逐场景 log10 E（V3 先验 / V2 先验 / GT）', '', '| 场景 | GT | 先验 V3 | 先验 V2 | +12 V3 | +12 V2 | 未来 CD +12 V3 | V2 |', '|---|---|---|---|---|---|---|---|']
    for s in SCENES:
        p = per_scene.get(s, {}); a0, a12 = p.get('prior20'), p.get('prior20_refine_b12')
        gt = new['part1'][s].get('gt_log10E')
        if a0 and a12:
            L.append(f"| {s} | {f(gt, 2)} | {f(a0['log10E']['v3'], 2)} | {f(a0['log10E']['v2'], 2)} | {f(a12['log10E']['v3'], 2)} | {f(a12['log10E']['v2'], 2)} | "
                     f"{f(a12['future_cd_mean']['v3'])} | {f(a12['future_cd_mean']['v2'])} |")
    L += ['', '## v3k-A：30 帧目标内修正，14 场景（\\|Δlog10 E\\| / Spearman / 成对排序）', '', '| 预算 | V3 先验起点 | V2 先验起点 | 配对差 V3−V2 [95% CI] |', '|---|---|---|---|']
    for k in KS:
        n, o = A['v3_prior'].get(f'k{k}'), A['v2_prior'].get(f'k{k}'); p = A['paired_v3_minus_v2'].get(f'k{k}')
        if n and o:
            L.append(f"| {k} | {n['mean_abs_dlog10E']:.2f} / {n['spearman']:.2f} / {n['pairwise_order_acc']:.2f} | {o['mean_abs_dlog10E']:.2f} / {o['spearman']:.2f} / {o['pairwise_order_acc']:.2f} | "
                     f"{p['mean_diff_abs_dlog10E_v3_minus_v2']:+.2f} [{p['ci95'][0]:+.2f}, {p['ci95'][1]:+.2f}] |" if p else '')
    L.append(f"无信息（jelly 训练均值，V2，沿用）起点：" + ' / '.join(f"k={k} {v:.2f}" for k, v in ((k[1:], v) for k, v in A['uninformed_jellymean_v2_REUSED'].items())))
    L += ['', '## PhysTwin single_push_sloth', '', '| 方法 | Chamfer 训练 | Chamfer 测试 | Track 训练 | Track 测试 |', '|---|---|---|---|---|']
    for t, lab in (('mpm_prior_b0', '先验起点，预算 0'), ('mpm_prior_b12', '先验 + 12 次')):
        L.append(f'| {lab}：V3（V2） | ' + ' | '.join(f"{f(pt[t][k]['v3'])} ({f(pt[t][k]['v2'])})" for k in pt_keys) + ' |')
    for t, lab in (('official_phystwin', 'PhysTwin 官方（沿用）'), ('rigid_follow', '刚性跟手（沿用）'), ('mpm_jellymean_b12', 'jelly 均值 + 12（沿用）')):
        L.append(f'| {lab} | ' + ' | '.join(f(pt[t + '_REUSED'][k]) for k in pt_keys) + ' |')
    L.append(f"\n先验 log10 E：V3 {f(pt['prior_log10E']['v3'], 2)}（V2 {f(pt['prior_log10E']['v2'], 2)}）；律投票 V3 {pt['law_votes']['v3']}；修正后 log10 E：V3 {f(pt['refined_log10E']['v3'], 2)}（V2 {f(pt['refined_log10E']['v2'], 2)}）。")
    (ROOT / 'docs/v3s/RESULTS_ZH.md').write_text('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
